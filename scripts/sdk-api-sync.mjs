// Build or verify docs/public-api.json from an AL-AI-Toolkit checkout.
//
//   pnpm docs:api-sync --sdk ../AL-AI-Toolkit   verify the manifest against a checkout
//   pnpm docs:api-sync --fetch                  clone the pinned commit into .cache/ and verify
//   pnpm docs:api-sync --sdk <path> --write     regenerate the manifest at the pinned commit
//   pnpm docs:api-sync --sdk <path> --pin       move the pin to the checkout HEAD and regenerate
//
// AIOS_SDK_PATH can replace --sdk. See docs-harness.md for when to use each mode.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { parseAlObjects } from './lib/al-source.mjs';
import { formatManifest, loadPin } from './lib/public-api.mjs';

const root = process.cwd();
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const option = (name) => {
  const index = args.indexOf(name);
  return index >= 0 ? args[index + 1] : undefined;
};

function git(cwd, ...gitArgs) {
  return execFileSync('git', ['-C', cwd, ...gitArgs], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
}

function fail(message) {
  console.error(`docs:api-sync: ${message}`);
  process.exit(1);
}

function walk(directory) {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (entry.name.endsWith('.al')) files.push(full);
  }
  return files.sort();
}

export function buildManifest(sdkRoot, pin, commit) {
  const apps = [];
  const objects = [];
  for (const app of pin.apps) {
    const appJson = JSON.parse(fs.readFileSync(path.join(sdkRoot, app.path, 'app.json'), 'utf8'));
    apps.push({ name: appJson.name, id: appJson.id, version: appJson.version, path: app.path, role: app.role });
    for (const file of walk(path.join(sdkRoot, app.path))) {
      const relative = path.relative(sdkRoot, file).split(path.sep).join('/');
      for (const object of parseAlObjects(fs.readFileSync(file, 'utf8'), relative)) {
        const clash = objects.find((o) => o.type === object.type && o.name === object.name);
        if (clash) fail(`duplicate ${object.type} ${object.name} in ${relative} and ${clash.file}`);
        objects.push({ app: appJson.name, role: app.role, ...object });
      }
    }
  }
  const key = (object) => `${object.name}\u0000${object.type}`;
  const sorted = objects.sort((a, b) => (key(a) < key(b) ? -1 : key(a) > key(b) ? 1 : 0));
  return {
    $comment: 'Generated by pnpm docs:api-sync from the pinned AL-AI-Toolkit commit. Do not edit by hand.',
    source: { repository: pin.repository, commit },
    objectPrefix: pin.objectPrefix,
    apps,
    objects: sorted,
  };
}

function resolveCheckout(pin) {
  if (flag('--fetch')) {
    const target = path.join(root, '.cache', 'al-ai-toolkit');
    if (!fs.existsSync(path.join(target, '.git'))) {
      fs.mkdirSync(target, { recursive: true });
      git(target, 'init', '-q');
      git(target, 'remote', 'add', 'origin', `${pin.repository}.git`);
    }
    git(target, 'fetch', '-q', '--depth', '1', 'origin', pin.commit);
    git(target, 'checkout', '-q', '--detach', 'FETCH_HEAD');
    return target;
  }
  const sdk = option('--sdk') ?? process.env.AIOS_SDK_PATH;
  if (!sdk) fail('pass --sdk <AL-AI-Toolkit checkout>, set AIOS_SDK_PATH, or use --fetch');
  const resolved = path.resolve(root, sdk);
  if (!fs.existsSync(path.join(resolved, 'apps'))) fail(`${resolved} is not an AL-AI-Toolkit checkout`);
  return resolved;
}

function describeDrift(current, next) {
  const lines = [];
  const byKey = (list) => new Map((list ?? []).map((object) => [`${object.type} "${object.name}"`, object]));
  const previous = byKey(current.objects);
  const upcoming = byKey(next.objects);
  for (const name of [...new Set([...previous.keys(), ...upcoming.keys()])].sort()) {
    const before = previous.get(name);
    const after = upcoming.get(name);
    if (!before) lines.push(`+ object ${name}`);
    else if (!after) lines.push(`- object ${name}`);
    else {
      const signatures = (object) =>
        new Set(
          [...object.procedures, ...object.events].map(
            (p) => `${p.access} ${p.name}(${p.params.map((x) => x.type).join('; ')})${p.returns ? `: ${p.returns}` : ''}`,
          ),
        );
      const a = signatures(before);
      const b = signatures(after);
      for (const s of b) if (!a.has(s)) lines.push(`+ ${name}: ${s}`);
      for (const s of a) if (!b.has(s)) lines.push(`- ${name}: ${s}`);
      if (before.access !== after.access) lines.push(`~ ${name}: access ${before.access} -> ${after.access}`);
    }
  }
  return lines;
}

function main() {
  const pinFile = path.join(root, 'docs/sdk-source.json');
  const pin = loadPin(root);
  const checkout = resolveCheckout(pin);
  const head = git(checkout, 'rev-parse', 'HEAD');

  if (flag('--pin')) {
    pin.commit = head;
    pin.commitDate = git(checkout, 'log', '-1', '--format=%cI');
    pin.commitSubject = git(checkout, 'log', '-1', '--format=%s');
  } else if (head !== pin.commit) {
    fail(
      `checkout is at ${head}, but docs/sdk-source.json pins ${pin.commit}.\n` +
        `Check out the pinned commit (git -C ${checkout} checkout ${pin.commit}), or run with --pin ` +
        'to move the docs to this revision and then re-verify every page that uses a changed API.',
    );
  }

  const dirty = git(checkout, 'status', '--porcelain', '--', ...pin.apps.map((app) => app.path));
  if (dirty) fail(`checkout has local changes under the pinned apps:\n${dirty}`);

  const next = buildManifest(checkout, pin, head);
  const manifestPath = path.join(root, pin.manifest);
  const current = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, 'utf8')) : {};

  if (flag('--write') || flag('--pin')) {
    if (flag('--pin')) fs.writeFileSync(pinFile, `${JSON.stringify(pin, null, 2)}\n`);
    fs.writeFileSync(manifestPath, formatManifest(next));
    const drift = describeDrift(current, next);
    console.log(`Wrote ${pin.manifest} for ${head} (${next.objects.length} objects).`);
    if (drift.length) console.log(`API changes since the previous manifest:\n${drift.join('\n')}`);
    console.log('Run pnpm docs:check and pnpm docs:api-review on every page that mentions a changed object.');
    return;
  }

  if (formatManifest(next) !== formatManifest(current)) {
    const drift = describeDrift(current, next);
    fail(
      `${pin.manifest} does not match the pinned source.\n${drift.join('\n') || '(signature order or anchors changed)'}\n` +
        'Run pnpm docs:api-sync --sdk <path> --write and commit the result.',
    );
  }
  console.log(`docs:api-sync: ${pin.manifest} matches ${pin.repository}@${head.slice(0, 12)}.`);
}

main();
